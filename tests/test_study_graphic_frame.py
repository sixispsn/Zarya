def study_case(kind):
    draft = {"revision": 0, "answers": {}, "documents": []}
    initialize_study(draft, kind, None)
    return build_study(draft)[1:3]


def engineering_svg(svg):
    """Exclude only border/notes/legend and the one moved outlet annotation."""
    root = ET.fromstring(svg)
    kept = []
    for element in root:
        if (element.get("data-study-legend") or element.text in
                ("Условные обозначения", "Указания к условному разрезу. Это не готовый ИОС3")
                or (element.tag.endswith("line") and element.get("y1") == "367.000")):
            break
        if element.tag.endswith("rect") and element.get("x") == "20" and element.get("y") == "5":
            continue  # old standalone outer frame, not engineering geometry
        for parent in element.iter():
            for child in list(parent):
                if child.get("data-leader-id") == "K1-outlet-note":
                    parent.remove(child)
        # CairoSVG registers the default namespace globally; prefix spelling
        # must not make this oracle depend on which renderer ran first.
        kept.append(ET.canonicalize(ET.tostring(element, encoding="unicode"),
                                   rewrite_prefixes=True).encode())
    return b"".join(kept)


def check_graphic_pdf(page, *, sheet_total=1):
    assert page.rect.width / mm == pytest.approx(594, abs=.01)
    assert page.rect.height / mm == pytest.approx(420, abs=.01)
    assert any(tuple(value / mm for value in drawing["rect"]) ==
               pytest.approx((404, 360, 589, 415), abs=.003)
               for drawing in page.get_drawings())
    assert region(page, 539, 390, 554, 400) == ""  # no assigned project stage
    assert region(page, 554, 390, 569, 400) == ("1" if sheet_total > 1 else "")
    assert region(page, 569, 390, 589, 400) == str(sheet_total)
    text = page.get_text()
    assert text.count("Изм.") == 1
    assert "Не для выпуска" in text
    assert "Формат А2" in text


@pytest.mark.parametrize("kind", ["compact", "plain", "calculated", "case"])
def test_a2_frame_keeps_geometry_and_model(kind):
    model, calculation = study_case("three" if kind == "case" else "two")
    before = deepcopy((model, calculation))
    svg = (build_residential_case_svg(model) if kind == "case" else
           build_small_residential_section_svg(model, calculation=calculation if kind != "plain" else None,
                                               compact_demo=kind == "compact"))
    validate_study_section_frame(svg)
    root = ET.fromstring(svg)
    assert len([e for e in root.iter() if e.get("data-sheet-border")]) == 1
    assert (model, calculation) == before
    # Fixed pre-migration snapshots, not regenerated by the frame implementation.
    expected = {
        "compact": "2b6950ac2557dd800279752d52ee4e7aef8e38de7631094d9a53a01be1a12a04",
        "plain": "888c28bc02b785da988252d48ab8d05669a2ade199413d5acca120f1641ee7db",
        "calculated": "b916197c460303c702604070dc384af5a0f56da801c0fb02d48219dca55492db",
        "case": "e9bc771b8a088c384107819350c67fc783c0718a4efdec097fb56cb224da3920",
    }
    assert sha256(engineering_svg(svg)).hexdigest() == expected[kind]
    ensure_drafting_font_registered()
    with fitz.open(stream=cairosvg.svg2pdf(bytestring=svg.encode()), filetype="pdf") as pdf:
        check_graphic_pdf(pdf[0])
    # Remove the opaque frame before rendering: it must not conceal body ink.
    root.remove(next(e for e in root if e.get("data-drawing-frame")))
    with fitz.open(stream=cairosvg.svg2pdf(bytestring=ET.tostring(root)), filetype="pdf") as pdf:
        stamp = fitz.Rect(399 * mm, 355 * mm, 589 * mm, 415 * mm)
        assert not pdf[0].get_text(clip=stamp).strip()
        pixels = pdf[0].get_pixmap(clip=stamp, colorspace=fitz.csGRAY, alpha=False)
        assert min(pixels.samples) == 255


def test_first_fan_control_sheet_has_real_total_without_changing_binding():
    model, binding = section_fan_fixture()
    original = deepcopy((model, binding))
    svg = build_small_residential_section_svg(model, fan_binding=binding)
    validate_study_section_frame(svg, sheet_total=binding.sheet_total)
    ensure_drafting_font_registered()
    with fitz.open(stream=cairosvg.svg2pdf(bytestring=svg.encode()), filetype="pdf") as pdf:
        check_graphic_pdf(pdf[0], sheet_total=binding.sheet_total)
    assert (model, binding) == original


@pytest.mark.parametrize("damage", ["missing", "height", "stage", "release", "format", "duplicate"])
def test_invalid_frame_cannot_be_exported(damage, tmp_path, monkeypatch):
    import app.pz.small_residential_section as section
    model, calculation = study_case("two")
    root = ET.fromstring(build_small_residential_section_svg(model, calculation=calculation, compact_demo=True))
    frame = next(e for e in root if e.get("data-drawing-frame"))
    if damage == "missing":
        root.remove(frame)
    elif damage == "duplicate":
        root.append(deepcopy(frame))
    elif damage == "height":
        stamp = next(e for e in frame if e.get("data-title-block"))
        stamp[0].set("height", "33")
    elif damage == "stage":
        next(e for e in frame.iter() if e.text == "Стадия").text = "Р"
    elif damage == "release":
        root.set("data-release-ready", "true")
    else:
        root.set("width", "420mm")
    monkeypatch.setattr(section, "build_small_residential_section_svg", lambda *a, **kw: ET.tostring(root, encoding="unicode"))
    path = tmp_path / "protected.pdf"
    path.write_bytes(b"existing user artifact")
    with pytest.raises(ValueError):
        section.generate_small_residential_section_pdf(str(path), model)
    assert path.read_bytes() == b"existing user artifact"


def test_notes_wrap_completely_or_fail_instead_of_clipping():
    notes = ["Явные исходные и ограничения. " * 8]
    svg = study_notes_svg(notes, x=25, y=365, width=100, bottom=411, height=2.5)
    assert " ".join(ET.fromstring(svg).itertext()).split() == notes[0].split()
    with pytest.raises(ValueError):
        study_notes_svg(notes * 10, x=25, y=365, width=100, bottom=411)
    with pytest.raises(ValueError):
        study_notes_svg(["X" * 1000], x=25, y=365, width=100, bottom=411)
