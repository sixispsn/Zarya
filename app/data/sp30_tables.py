def get_alpha(np_value: float) -> float:
    """Коэффициент Б.2: таблица и прежняя линейная интерполяция.

    NP < 0.015: 0.200 (включая прежнюю защиту для NP <= 0).
    NP = 0.015: 0.202; NP = 2000: 426.80 — точные крайние ячейки.
    Выше 2000 расчёт прекращается: нормативной экстраполяции нет.
    Это исправление Б.2, не реализация области применения таблицы Б.1.
    """
    if not math.isfinite(np_value):
        raise ValueError("NP для таблицы Б.2 должен быть конечным числом.")
    if np_value < ALPHA_TABLE[0][0]:
        return 0.200
    if np_value > ALPHA_TABLE[-1][0]:
        raise ValueError(
            f"NP={np_value:g} выходит за предел таблицы Б.2 СП 30 (2000). "
            "Требуется отдельное обоснование расчёта; экстраполяция не применяется."
        )

    for np1, a1 in ALPHA_TABLE:
        if np_value == np1:
            return a1
    for (np1, a1), (np2, a2) in zip(ALPHA_TABLE, ALPHA_TABLE[1:]):
        if np1 < np_value < np2:
            k = (np_value - np1) / (np2 - np1)
            return a1 + k * (a2 - a1)
    raise AssertionError("Нарушена полнота диапазона таблицы Б.2")


